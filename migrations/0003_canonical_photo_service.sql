CREATE TABLE people (
  slug TEXT PRIMARY KEY,
  display_name TEXT NOT NULL,
  is_public INTEGER NOT NULL DEFAULT 0 CHECK (is_public IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE photo_people (
  photo_id TEXT NOT NULL REFERENCES photos(id) ON DELETE RESTRICT,
  person_slug TEXT NOT NULL REFERENCES people(slug) ON DELETE CASCADE,
  position INTEGER,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (photo_id, person_slug)
);

CREATE INDEX idx_photo_people_person ON photo_people(person_slug, position);

