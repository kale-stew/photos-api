-- Canonical identity, publication, and deletion-safety model.

ALTER TABLE photos ADD COLUMN status TEXT NOT NULL DEFAULT 'active'
  CHECK (status IN ('active', 'quarantined'));
ALTER TABLE photos ADD COLUMN visibility TEXT NOT NULL DEFAULT 'public'
  CHECK (visibility IN ('public', 'unlisted', 'private'));

CREATE INDEX idx_photos_status_visibility ON photos(status, visibility);
CREATE UNIQUE INDEX idx_photos_r2_key ON photos(r2_key);

CREATE TABLE photo_aliases (
  alias TEXT PRIMARY KEY,
  photo_id TEXT NOT NULL REFERENCES photos(id) ON DELETE RESTRICT,
  kind TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_photo_aliases_photo_id ON photo_aliases(photo_id);

CREATE TRIGGER photo_aliases_reject_canonical_id
BEFORE INSERT ON photo_aliases
WHEN EXISTS (SELECT 1 FROM photos WHERE id = NEW.alias)
BEGIN
  SELECT RAISE(ABORT, 'alias conflicts with canonical photo id');
END;

CREATE TRIGGER photo_aliases_reject_canonical_id_update
BEFORE UPDATE OF alias ON photo_aliases
WHEN EXISTS (SELECT 1 FROM photos WHERE id = NEW.alias)
BEGIN
  SELECT RAISE(ABORT, 'alias conflicts with canonical photo id');
END;

CREATE TRIGGER photos_reject_existing_alias
BEFORE INSERT ON photos
WHEN EXISTS (SELECT 1 FROM photo_aliases WHERE alias = NEW.id)
BEGIN
  SELECT RAISE(ABORT, 'canonical photo id conflicts with alias');
END;

CREATE TRIGGER photos_reject_existing_alias_update
BEFORE UPDATE OF id ON photos
WHEN EXISTS (SELECT 1 FROM photo_aliases WHERE alias = NEW.id)
BEGIN
  SELECT RAISE(ABORT, 'canonical photo id conflicts with alias');
END;

-- Notion page IDs are authoritative legacy identifiers carried through the
-- original migration. Short aliases are generated by the audited backfill.
INSERT INTO photo_aliases (alias, photo_id, kind)
SELECT notion_id, id, 'notion-id'
FROM photos
WHERE notion_id IS NOT NULL AND notion_id != '' AND notion_id != id;

CREATE TABLE collections (
  slug TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  is_public INTEGER NOT NULL DEFAULT 0 CHECK (is_public IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE photo_collections (
  photo_id TEXT NOT NULL REFERENCES photos(id) ON DELETE RESTRICT,
  collection_slug TEXT NOT NULL REFERENCES collections(slug) ON DELETE CASCADE,
  position INTEGER,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (photo_id, collection_slug)
);

CREATE INDEX idx_photo_collections_collection
  ON photo_collections(collection_slug, position);

